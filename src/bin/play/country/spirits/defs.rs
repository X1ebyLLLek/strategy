//! The catalogue of features: each one's name, icon and tone, the facts that call it up (`want`),
//! why it is there in words (`why`) and what it does (`eff`).

use super::*;

pub(super) fn ramp(x: f32, lo: f32, hi: f32) -> f32 {
    ((x - lo) / (hi - lo)).clamp(0.0, 1.0)
}

pub(super) fn pc(x: f32) -> String {
    format!("{:.0}%", x * 100.0)
}

pub(super) fn years(y: f32) -> String {
    let n = y.round().max(1.0) as usize;
    format!("{n} {}", crate::words::plural(n, "год", "года", "лет"))
}

pub(super) fn e() -> Eff {
    Eff::default()
}

/// How long ago, in words (the folders show no figures: those are on the cards).
pub(super) fn ago_words(y: f32) -> &'static str {
    match y {
        y if y < 3.0 => "совсем недавно",
        y if y < 8.0 => "несколько лет назад",
        y if y < 15.0 => "лет десять назад",
        y if y < 30.0 => "четверть века назад",
        y if y < 60.0 => "полвека назад",
        _ => "давным-давно",
    }
}

