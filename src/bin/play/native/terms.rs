/// A word with its note on hover (underlined, in the accent's colour).
pub fn term(ui: &mut egui::Ui, s: &Skin, word: &str, key: &str) -> egui::Response {
    let r = ui.add(egui::Label::new(RichText::new(word).underline().color(s.accent)).sense(egui::Sense::hover()));
    match note(key) {
        Some((title, text)) => r.tip(|| Card::new(title).icon("scroll").text(text).note("слово игры")),
        None => r,
    }
}

/// A sentence of plain words and words with notes (`[key]word` marks a word with a note,
/// `[key]{two words}` several), wrapped as text is.
pub fn say(ui: &mut egui::Ui, s: &Skin, text: &str) {
    ui.horizontal_wrapped(|ui| {
        ui.spacing_mut().item_spacing.x = 0.0;
        let mut rest = text;
        while let Some(i) = rest.find('[') {
            if i > 0 {
                ui.label(&rest[..i]);
            }
            let Some(j) = rest[i..].find(']') else { break };
            let key = &rest[i + 1..i + j];
            let after = &rest[i + j + 1..];
            if let Some(words) = after.strip_prefix('{') {
                let end = words.find('}').unwrap_or(words.len());
                term(ui, s, &words[..end], key);
                rest = words.get(end + 1..).unwrap_or("");
                continue;
            }
            // the word runs to the next space or mark
            let end = after.find(|c: char| c.is_whitespace() || c == ',' || c == '.' || c == '—' || c == ';' || c == ':' || c == '(' || c == ')').unwrap_or(after.len());
            term(ui, s, &after[..end], key);
            rest = &after[end..];
        }
        if !rest.is_empty() {
            ui.label(rest);
        }
    });
}
